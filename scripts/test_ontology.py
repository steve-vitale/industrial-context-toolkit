def quiet(fn, *a, **k):
    with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
        return fn(*a, **k)


def write_pasteurizer(out):
    """Build the pasteurizer example and write its JSON-LD view and the answers to QUESTIONS next to it."""
    out = Path(out)
    g, _, _, _ = quiet(om.build, PAST / "site.json", out, full=True)
    doc = onto_mod.to_jsonld(g, onto_mod.Ontology.load())
    (out / "map.jsonld").write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n", encoding="utf-8",
                                    newline="\n")
    lines = ["# Answers from the pasteurizer map", "",
             "Generated by `one_map.py ask --map graph.json --question-kind KIND --item ITEM` for each question below "
             "(read-only; every answer carries its source, and an answer the map cannot give says which record is "
             "missing for which scope).", "", "```text"]
    for kind, item in QUESTIONS:
        lines.append(f"$ one_map.py ask --question-kind {kind} --item \"{item}\"")
        lines.append(onto_mod.ask_text(onto_mod.ask(g, kind, item)).rstrip("\n"))
        lines.append("")
    lines[-1] = "```"
    (out / "answers.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return g


def rows_of(path):
    return list(csv.DictReader(io.StringIO(Path(path).read_text(encoding="utf-8"))))


class Classes(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.onto = onto_mod.Ontology.load()

    def test_tree_is_complete_and_acyclic_with_standard_refs(self):
        ids = set(self.onto.classes)
        for needed in ("equipment", "rotating_equipment", "pump", "centrifugal_pump", "positive_displacement_pump",
                       "static_equipment", "vessel_tank", "heat_exchanger", "plate_heat_exchanger",
                       "shell_tube_heat_exchanger", "hold_tube", "valve", "control_valve", "on_off_valve",
                       "divert_valve", "relief_device", "instrument", "transmitter", "controller", "line", "document",
                       "pid", "procedure", "verification_record"):
            self.assertIn(needed, ids)
        for c in self.onto.classes.values():
            self.assertLess(len(self.onto.ancestors(c["id"])), 8, c["id"])
            self.assertEqual(c["cfihos"]["id_status"], "to_confirm", c["id"])
            self.assertIsNone(c["cfihos"]["ref"], "no CFIHOS code is shipped")
            if c.get("dexpi"):
                self.assertEqual(c["dexpi"]["id_status"], "verified")
                for u in c["dexpi"]["uris"]:
                    self.assertRegex(u, r"^https://dexpi\.org/specification/2\.0\.1/html/models/Plant/"
                                        r"(ProcessEquipment|Piping|Instrumentation)/[A-Za-z]+\.html$")
            self.assertTrue(onto_mod.certified(c["certification"]), c["id"])
            for p in c.get("refine", {}).get("values", {}).values():
                self.assertTrue(self.onto.is_a(p, c["id"]) and p != c["id"], f"{c['id']} refines sideways to {p}")
        self.assertTrue(self.onto.is_a("centrifugal_pump", "equipment"))
        self.assertFalse(self.onto.is_a("divert_valve", "equipment"))

    def test_inference_is_deterministic_and_only_where_the_letters_say(self):
        inf = self.onto.infer
        self.assertEqual(inf("FDV-2210", "equipment")[0], "divert_valve")
        self.assertEqual(inf("PSV-2215", "relief_device")[0], "relief_device")
        self.assertEqual(inf("TT-2207", "instrument")[0], "transmitter")
        self.assertEqual(inf("TIC-2207", "controller")[0], "controller")
        self.assertEqual(inf("FCV-10", "final_element")[0], "control_valve")
        self.assertEqual(inf("XV-12", "final_element")[0], "on_off_valve")
        self.assertEqual(inf("PI-2240", "instrument")[0], "indicator")
        self.assertEqual(inf("P-101", "equipment")[0], "pump")
        self.assertEqual(inf("P-101", "equipment", {"pump_type": "Rotary Lobe"})[0], "positive_displacement_pump")
        self.assertEqual(inf("P-102", "equipment", {"pump_type": "centrifugal"})[0], "centrifugal_pump")
        self.assertEqual(inf("HT-100", "equipment")[0], "hold_tube")
        self.assertEqual(inf("E-2215", "equipment", {"exchanger_type": "plate"})[0], "plate_heat_exchanger")
        # not deterministic: unknown prefix, prefix on a non-equipment, letters that do not fit the kind, no digits
        for tag, kind in (("FL-401", "equipment"), ("P-101", "instrument"), ("TT-2207", "equipment"),
                          ("MSCV-XXX", "final_element"), ("CW", "equipment")):
            self.assertIsNone(inf(tag, kind)[0], (tag, kind))
        # a datasheet value never refines sideways (a pump is never made a tank)
        self.assertEqual(inf("P-1", "equipment", {"type": "tank"})[0], "pump")
        # explicit record class wins; an unknown one is reported, not assigned
        self.assertEqual(inf("X-1", "equipment", explicit="hold_tube"), ("hold_tube", "record column class"))
        self.assertIsNone(inf("X-1", "equipment", explicit="spaceship")[0])

    def test_site_overrides_and_draft_classes(self):
        onto = onto_mod.Ontology.load(letter_overrides={"HT": "hold_tube", "SC": "controller"},
                                      equipment_prefixes={"FL": "tank"})
        self.assertEqual(onto.infer("FL-401", "equipment")[0], "tank")
        self.assertIsNone(onto.infer("P-1", "equipment")[0], "the site's prefixes replace the defaults")
        self.assertEqual(onto.infer("SC-101", "controller")[0], "controller")
        doc = json.loads(onto_mod.CLASSES.read_text(encoding="utf-8"))
        extra = [{"id": "filler", "parent": "equipment", "label": "Filler", "definition": "x",
                  "certification": {"status": "draft"}}]
        onto2 = onto_mod.Ontology(doc, json.loads(onto_mod.RELATIONS.read_text(encoding="utf-8")),
                                  equipment_prefixes={"FL": "filler"}, extra_classes=extra)
        self.assertIsNone(onto2.infer("FL-401", "equipment")[0], "a draft class is never assigned")
        with self.assertRaises(onto_mod.OntologyError):
            onto_mod.Ontology.load(letter_overrides={"ZZ": "no_such_class"})


class Relations(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.onto = onto_mod.Ontology.load()
        cls.rel = json.loads(onto_mod.RELATIONS.read_text(encoding="utf-8"))
        cls.schema = json.loads((onto_mod.DIR / "context-map-1.schema.json").read_text(encoding="utf-8"))

    def test_every_frozen_relation_has_semantics(self):
        frozen = set(self.schema["$defs"]["RelationType"]["enum"]) | {"covers", "mentions", "based_on"}
        self.assertEqual(set(self.onto.relations), frozen)
        inverses = [r["inverse"] for r in self.rel["relations"]]
        self.assertEqual(len(inverses), len(set(inverses)))
        self.assertFalse(set(inverses) & frozen, "an inverse name must not reuse a frozen relation name")
        card = re.compile(r"^(0\.\.1|1|0\.\.\*|1\.\.\*)$")
        for r in self.rel["relations"]:
            self.assertIsInstance(r["transitive"], bool)
            for side in ("per_from", "per_to"):
                self.assertRegex(r["cardinality"][side], card)
            for c in r["domain"] + r["range"]:
                self.assertTrue(c in self.onto.classes or c in self.rel["pseudo_classes"], (r["name"], c))
        self.assertTrue(self.onto.relations["contains"]["transitive"])
        self.assertTrue(self.onto.relations["based_on"]["transitive"])
        self.assertFalse(self.onto.relations["piped_to"]["transitive"])
        for edge, rel in self.rel["twin_graph_2_edges"].items():
            self.assertTrue(rel is None or rel in self.onto.relations, edge)

    def test_check_link(self):
        c = lambda x: ("class", x)  # noqa: E731
        self.assertIsNone(self.onto.check_link("measures", c("transmitter"), c("hold_tube")))
        self.assertIn("not controller", self.onto.check_link("measures", c("indicator"), c("controller")))
        self.assertIn("starts at", self.onto.check_link("protects", c("pump"), c("vessel")))
        self.assertIsNone(self.onto.check_link("controls", c("controller"), c("divert_valve")))
        self.assertIsNone(self.onto.check_link("contains", ("pseudo", "@scope"), c("pump")))
        self.assertEqual(self.onto.check_link("measures", (None, None), c("pump")), "unchecked")
        # twin-graph-1's measurement -> controller `controls` reads as signal_to
        self.assertEqual(self.onto.relation_for_edge("controls", "transmitter"), "signal_to")
        self.assertEqual(self.onto.relation_for_edge("controls", "controller"), "controls")
        # a run between tagged ends is network co-membership, never pipe adjacency (relations.json 1.2)
        self.assertEqual(self.onto.relation_for_edge("connects", None), "network_member")
        self.assertIsNone(self.onto.relation_for_edge("concerns", None))

    def test_cardinality_upper_bound(self):
        nodes = {i: {"id": i, "kind": "instrument" if i == "T" else "equipment", "class": c}
                 for i, c in (("T", "transmitter"), ("A", "vessel"), ("B", "pump"))}
        edges = [{"id": "1", "type": "measures", "from": "T", "to": "A"},
                 {"id": "2", "type": "measures", "from": "T", "to": "B"}]
        found, counts = onto_mod.check_links(nodes, edges, self.onto)
        self.assertEqual(counts["do_not_fit"], 1)
        self.assertIn("at most one target", found[0]["why"])


class Pasteurizer(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory()
        cls.out = Path(cls.tmp.name) / "pasteurizer"
        cls.g = write_pasteurizer(cls.out)
        cls.nodes = {n["id"]: n for n in cls.g["nodes"]}
        cls.rows = rows_of(cls.out / "queues" / "review_queue.csv")

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def kind(self, k):
        return [r for r in self.rows if r["kind"] == k]

    def test_expected_outputs_regenerate_byte_for_byte(self):
        files = sorted(p for p in EXPECTED.rglob("*") if p.is_file())
        self.assertEqual({p.relative_to(EXPECTED).as_posix() for p in files},
                         {"graph.json", "report.md", "conflicts.md", "queues/review_queue.csv", "map.jsonld",
                          "answers.md"})
        for exp in files:
            rel = exp.relative_to(EXPECTED)
            self.assertEqual((self.out / rel).read_bytes().replace(b"\r\n", b"\n"),
                             exp.read_bytes().replace(b"\r\n", b"\n"), rel)
        self.assertEqual(om.problems(self.g), [])

    def test_classes_on_items(self):
        want = {"S1/P1/PAST1/P-101": "positive_displacement_pump", "S1/P1/PAST1/P-102": "centrifugal_pump",
                "S1/P1/PAST1/HT-100": "hold_tube", "S1/P1/PAST1/FDV-2210": "divert_valve",
                "S1/P1/PAST1/E-2215": "shell_tube_heat_exchanger", "S1/P1/PAST1/TT-2207": "transmitter",
                "S1/DOC/VER-CCP1": "verification_record", "S1/DOC/PID-P1-PAST1-01": "pid"}
        for nid, c in want.items():
            self.assertEqual(self.nodes[nid].get("class"), c, nid)
        self.assertEqual(self.nodes["S1/P1/PAST1/E-2215"]["class_how"], "record column class")
        self.assertNotIn("class", self.nodes["S1/P1/FILL1/FL-401"], "not deterministic: left unset")

    def test_link_that_does_not_fit_is_a_review_row_and_is_kept(self):
        rows = self.kind(onto_mod.LINK_ROW)
        self.assertEqual([(r["item"], r["owner"]) for r in rows], [("S1/P1/PAST1/PI-2240", "Doc control")])
        self.assertIn("PI-2240 (indicator) measures TIC-2207 (controller)", rows[0]["why"])
        self.assertTrue(any(e["type"] == "measures" and e["from"] == "S1/P1/PAST1/PI-2240" for e in self.g["edges"]))

    def test_expectation_rows_by_rule(self):
        rows = self.kind(onto_mod.MISSING_ROW)
        by_rule = sorted((r["why"].split(" ", 1)[0], r["item"], r["owner"]) for r in rows)
        self.assertEqual(by_rule, [
            ("R-CCP-COMPLETE", "S1/P1/PAST1/FT-2203", "Quality"),
            ("R-CRITICAL-PM", "S1/P1/PAST1/FDV-2210", "Maintenance"),
            ("R-CRITICAL-PM", "S1/P1/PAST1/P-101", "Maintenance"),
            ("R-RELIEF-PROTECTS", "S1/P1/PAST1/PSV-2216", "Process safety")])
        ccp = next(r for r in rows if "R-CCP-COMPLETE" in r["why"])
        for words in ("a critical limit", "next_due 2026-08-01 before 2026-11-04", "no verification_record document"):
            self.assertIn(words, ccp["why"])
        self.assertEqual(ccp["safety"], "CCP monitoring instrument (CCP-2)")
        self.assertEqual(ccp["tier"], "amber")
        res = {(r["rule"], r["subject"]): r for r in self.g["expectations"]["results"]}
        self.assertEqual(res[("R-CCP-COMPLETE", "S1/P1/PAST1/TT-2207")]["status"], "complete")
        # an absent register makes a check not evaluable, never a missing row
        cip = res[("R-RELIEF-PROTECTS", "S1/P1/CIP1/PSV-3101")]
        self.assertEqual(cip["status"], "not_evaluable")
        self.assertIn("no relief_device_register or inspection_record covers S1/P1/CIP1", cip["not_evaluable"][0])
        # rollout: certified, but not rolled out to CIP1
        self.assertEqual(res[("R-CRITICAL-PM", "S1/P1/CIP1/P-301")]["status"], "not_rolled_out")
        # draft rule: one summary row per scope, no per-item row
        draft = self.kind(onto_mod.DRAFT_RULE_ROW)
        self.assertEqual([(r["item"], r["owner"]) for r in draft], [("S1/P1/PAST1", "I&C")])
        self.assertIn("would raise 1", draft[0]["why"])
        self.assertEqual(res[("R-LOOP-COMPLETE", "S1/P1/PAST1/PIC-2240")]["status"], "draft_rule")
        cov = {c["rule"]: c for c in self.g["expectations"]["by_rule"]}
        self.assertEqual((cov["R-CRITICAL-PM"]["missing"], cov["R-CRITICAL-PM"]["not_rolled_out"],
                          cov["R-CRITICAL-PM"]["rows_raised"]), (2, 1, 2))
        self.assertEqual(cov["R-PID-IN-CMMS"]["rows_raised"], 0, "the reused conflict kind raises no second row")

    def test_glossary_links_and_reviews(self):
        links = {}
        for e in self.g["edges"]:
            a = {c["name"]: c["value"] for c in e.get("attributes", [])}
            if e["type"] == "mentions" and a.get("matched") == "glossary":
                links.setdefault(e["from"], set()).add((e["to"], a["glossary_term"]))
        self.assertEqual(links["S1/DOC/HACCP-PLAN-P1"], {("S1/P1/PAST1", "HTST"), ("S1/P1/PAST1/HT-100", "hold tube"),
                                                         ("S1/P1/PAST1/FDV-2210", "divert valve")})
        self.assertIn(("S1/P1/PAST1/FDV-2210", "divert valve"), links["S1/DOC/SOP-PAST1-02"])  # synonym FDV
        reviews = [r for r in self.kind(om.CONFIRM) if r["item"] == "S1/DOC/SOP-PAST1-02"]
        whys = " | ".join(r["why"] for r in reviews)
        self.assertIn("'timing pump' is draft, not certified", whys)
        self.assertIn("'product pump' maps to 2 items", whys)
        self.assertTrue(all(r["owner"] == "Production" for r in reviews), "routed to the term's owner")
        self.assertFalse(any(e["type"] == "mentions" and e["to"] == "S1/P1/PAST1/P-101" for e in self.g["edges"]))

    def test_answers(self):
        g = self.g
        a = onto_mod.ask(g, "measured-by", "hold tube")
        self.assertEqual(a["item"], "S1/P1/PAST1/HT-100")
        self.assertEqual(a["facts"][0]["source"]["document"], "S1/DOC/PID-P1-PAST1-01")
        a = onto_mod.ask(g, "connects", "FL-401")
        self.assertEqual(a["answer"], onto_mod.NOT_FOUND)
        self.assertIn("no P&ID covers S1/P1/FILL1", a["reason"])
        a = onto_mod.ask(g, "complete", "PSV-3101")
        self.assertIn("can't answer from this map: no relief_device_register", a["facts"][0]["says"])
        a = onto_mod.ask(g, "complete", "P-102")
        self.assertEqual(a["answer"], onto_mod.NOT_FOUND)
        a = onto_mod.ask(g, "documents", "FDV-2210")
        self.assertTrue(any("as 'FDV'" in f["says"] for f in a["facts"]))
        self.assertIsNone(onto_mod.ask(g, "connects", "timing pump")["item"], "a draft term resolves nothing")
        with self.assertRaises(onto_mod.OntologyError):
            onto_mod.ask(g, "why", "P-101")
        # read-only: the graph is unchanged by asking
        before = json.dumps(g, sort_keys=True)
        for kind, item in QUESTIONS:
            onto_mod.ask(g, kind, item)
        self.assertEqual(json.dumps(g, sort_keys=True), before)

    def test_disagreements_need_two_records(self):
        g = copy.deepcopy(self.g)
        n = next(x for x in g["nodes"] if x["id"] == "S1/P1/FILL1/FL-401")
        a = onto_mod.ask(g, "disagreements", "FL-401")
        self.assertEqual(a["answer"], onto_mod.NOT_FOUND)
        self.assertIn("only 1 record holds FL-401", a["reason"])
        self.assertTrue(n)

    def test_jsonld_view(self):
        doc = json.loads((self.out / "map.jsonld").read_text(encoding="utf-8"))
        by_id = {x["@id"]: x for x in doc["@graph"]}
        ht = by_id["urn:context-map:S1/P1/PAST1/HT-100"]
        self.assertIn("cm:class/hold_tube", ht["@type"])
        # the sheet's run HT-100 -> FDV-2210 is network co-membership, not proven pipe adjacency (relations.json 1.2)
        self.assertEqual(ht["network_member"], ["urn:context-map:S1/P1/PAST1/FDV-2210"])
        self.assertNotIn("piped_to", ht)
        pump = by_id["cm:class/centrifugal_pump"]
        self.assertEqual(pump["seeAlso"], ["https://dexpi.org/specification/2.0.1/html/models/Plant/ProcessEquipment/"
                                           "CentrifugalPump.html"])
        self.assertEqual(pump["cm:cfihos"], "to_confirm")
        stm = [x for x in doc["@graph"] if x.get("@type") == "cm:Statement"]
        self.assertTrue(stm and all(s["cm:source"] or s["cm:relation"]["@id"] == "cm:contains" for s in stm))
        self.assertTrue(any(s["cm:relation"]["@id"] == "cm:signal_to" for s in stm), "loop list controls -> signal_to")


class Variants(unittest.TestCase):
    """Build variants of the pasteurizer example in a temporary copy."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.dir = Path(self.tmp.name) / "p"
        shutil.copytree(PAST, self.dir)
        self.site = json.loads((self.dir / "site.json").read_text(encoding="utf-8"))
        self.rules = json.loads((self.dir / "expectations.json").read_text(encoding="utf-8"))

    def tearDown(self):
        self.tmp.cleanup()

    def build(self):
        (self.dir / "site.json").write_text(json.dumps(self.site), encoding="utf-8")
        (self.dir / "expectations.json").write_text(json.dumps(self.rules), encoding="utf-8")
        g, _, rows, _ = quiet(om.build, self.dir / "site.json", Path(self.tmp.name) / "out", full=True)
        return g, rows

    def test_shipped_template_rules_are_all_draft_and_raise_only_summaries(self):
        self.rules = json.loads(onto_mod.RULES_TEMPLATE.read_text(encoding="utf-8"))
        self.rules["as_of"] = "2026-11-04"
        g, rows = self.build()
        self.assertFalse([r for r in rows if r["kind"] == onto_mod.MISSING_ROW])
        draft = [r for r in rows if r["kind"] == onto_mod.DRAFT_RULE_ROW]
        self.assertEqual(sorted(r["why"].split(" ", 1)[0] for r in draft),
                         ["R-CCP-COMPLETE", "R-CRITICAL-PM", "R-CRITICAL-PM", "R-LOOP-COMPLETE",
                          "R-RELIEF-PROTECTS"])  # one per rule and scope (critical PM: PAST1 and CIP1)

    def test_rollout_by_owner_and_limit_per_scope(self):
        self.rules["rollout"] = {"owners": ["Quality"], "scopes": None}
        g, rows = self.build()
        self.assertEqual({r["owner"] for r in rows if r["kind"] == onto_mod.MISSING_ROW}, {"Quality"})
        self.rules["rollout"] = {"owners": None, "scopes": None}
        for r in self.rules["rules"]:
            if r["id"] == "R-CRITICAL-PM":
                r["limit_per_scope"] = 1
        g, rows = self.build()
        pm = [r for r in rows if r["kind"] == onto_mod.MISSING_ROW and "R-CRITICAL-PM" in r["why"]]
        self.assertEqual(len(pm), 2)
        self.assertTrue(any("1 more subject(s)" in r["why"] for r in pm))

    def test_no_as_of_date_means_date_checks_are_not_evaluated(self):
        self.rules["as_of"] = None
        self.site.pop("as_of")
        g, _ = self.build()
        res = {(r["rule"], r["subject"]): r for r in g["expectations"]["results"]}
        tt = res[("R-CCP-COMPLETE", "S1/P1/PAST1/TT-2207")]
        self.assertEqual(tt["status"], "not_evaluable")
        self.assertIn("no as_of date", tt["not_evaluable"][0])

    def test_certified_without_who_and_when_is_draft(self):
        for r in self.rules["rules"]:
            r["certification"] = {"status": "certified"}
        _, rows = self.build()
        self.assertFalse([r for r in rows if r["kind"] == onto_mod.MISSING_ROW])
        self.assertTrue(all("without who and when" in r["why"] for r in rows if r["kind"] == onto_mod.DRAFT_RULE_ROW))

    def test_bad_rules_and_records_are_refused(self):
        self.rules["rules"][0]["checks"][0]["check"] = "guess"
        with self.assertRaises(om.InputError):
            self.build()
        self.rules = json.loads((PAST / "expectations.json").read_text(encoding="utf-8"))
        self.site["records"].append({"id": "X", "register": "spreadsheet", "path": "records/ccp.csv"})
        with self.assertRaises(om.InputError):
            self.build()

