"""Package a completed original UI attempt, retaining exact omitted cache bytes."""
import argparse
from pathlib import Path
from tempfile import TemporaryDirectory
from campaign import HERE, read, write, sha, require
from native_ui import receiving
from retain import package


def retain(attempt,host,name):
    require(read(host/'EXIT.json')['exit']==0,'Original UI host did not finish normally')
    result=receiving(attempt);require(name==result['case']+'-'+result['role'],'UI packet name differs')
    out=HERE/'ui-evidence'/name
    pin=package([('attempt',attempt),('execution',host)],out,result)
    # These are the actual original runtime files, not regenerated bytecode.
    with TemporaryDirectory(prefix='ict-original-ui-runtime-') as temporary:
        folder=Path(temporary)
        for path in (attempt/'job/__pycache__').rglob('*'):
            if path.is_file():
                dest=folder/'attempt/job/__pycache__'/path.relative_to(attempt/'job/__pycache__')
                dest.parent.mkdir(parents=True,exist_ok=True);dest.write_bytes(path.read_bytes())
        support=package([('',folder)],out/'runtime-support',exclude_runtime=False)
    pins=read(HERE/'UI-RETAINED.json');require(name not in pins['attempts'],'Original UI packet already registered')
    pins['attempts'][name]=dict(pin,result_sha256=sha(out/'RESULT.json'),runtime_support=support)
    write(HERE/'UI-RETAINED.json',pins)
    return result


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    for name in ('attempt','host'):p.add_argument(name,type=Path)
    p.add_argument('name');a=p.parse_args();r=retain(a.attempt,a.host,a.name)
